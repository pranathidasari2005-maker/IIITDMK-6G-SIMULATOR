    @app.route("/resend-verification", methods=["POST"])
    def resend_verification():
        import time

        if not valid_csrf():
            flash("Your session expired. Please try again.", "error")
            return redirect(url_for("login"))

        email = request.form.get("email", "").strip().lower()

        if not allow_verification_resend(login_client_ip()):
            flash("Too many requests. Try again in 15 minutes.", "error")
            return redirect(url_for("login"))

        if re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", email):
            with get_db() as db:
                user = db.execute(
                    """
                    SELECT id, username, email, email_verified
                    FROM users WHERE email = ? COLLATE NOCASE
                    """,
                    (email,)
                ).fetchone()

                if user and not user["email_verified"]:
                    code = f"{secrets.randbelow(1_000_000):06d}"
                    code_hash = hmac.new(
                        str(app.secret_key).encode(),
                        code.encode(),
                        hashlib.sha256
                    ).hexdigest()

                    db.execute(
                        "DELETE FROM email_verification_tokens WHERE user_id = ?",
                        (user["id"],)
                    )
                    db.execute(
                        """
                        INSERT INTO email_verification_tokens
                            (user_id, token_hash, expires_at)
                        VALUES (?, ?, ?)
                        """,
                        (user["id"], code_hash, time.time() + 600)
                    )

                    try:
                        send_auth_email(
                            user["email"],
                            "Your IIITDMK 6G Simulator verification code",
                            (
                                f"Hello {user['username']},\n\n"
                                f"Your new verification code is: {code}\n\n"
                                "It expires in 10 minutes. Your previous code is no longer valid."
                            )
                        )
                    except Exception:
                        app.logger.exception(
                            "Could not resend verification code to %s",
                            user["email"]
                        )

            session["pending_verification_email"] = email

        flash(
            "If your account exists and needs verification, a new code will be sent.",
            "success"
        )
        return redirect(url_for("verify_email", email=email))


    @app.route("/forgot-password", methods=["GET", "POST"])
    def forgot_password():
        if session.get("user_id"):
            return redirect(url_for("index"))

        if request.method == "POST":
            if not valid_csrf():
                flash("Your session expired. Please try again.", "error")
                return redirect(url_for("forgot_password"))

            email_address = request.form.get("email", "").strip().lower()
            ip_address = login_client_ip()

            if allow_password_reset_request(ip_address):
                if re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", email_address):
                    with get_db() as db:
                        user = db.execute(
                            "SELECT id, email FROM users WHERE email = ? COLLATE NOCASE",
                            (email_address,)
                        ).fetchone()

                    if user:
                        raw_token = secrets.token_urlsafe(32)
                        token_hash = hashlib.sha256(raw_token.encode()).hexdigest()
                        import time
                        now = time.time()

                        with get_db() as db:
                            db.execute(
                                "DELETE FROM password_reset_tokens WHERE user_id = ?",
                                (user["id"],)
                            )
                            db.execute(
                                """INSERT INTO password_reset_tokens
                                   (user_id, token_hash, expires_at)
                                   VALUES (?, ?, ?)""",
                                (user["id"], token_hash, now + 1800)
                            )

                        base_url = os.environ.get(
                            "PUBLIC_BASE_URL", request.url_root.rstrip("/")
                        ).rstrip("/")
                        reset_url = (
                            base_url + url_for("reset_password", token=raw_token)
                        )

                        try:
                            send_password_reset_email(user["email"], reset_url)
                        except Exception:
                            app.logger.exception("Password reset email delivery failed")
                            with get_db() as db:
                                db.execute(
                                    "DELETE FROM password_reset_tokens WHERE token_hash = ?",
                                    (token_hash,)
                                )

            flash(
                "If an account exists for that email, a password reset link will be sent.",
                "success"
            )
            return redirect(url_for("forgot_password"))

        return render_template("forgot_password.html")

    @app.route("/reset-password/<token>", methods=["GET", "POST"])
    def reset_password(token):
        if session.get("user_id"):
            return redirect(url_for("index"))

        token_hash = hashlib.sha256(token.encode()).hexdigest()
        import time
        now = time.time()

        with get_db() as db:
            reset_record = db.execute(
                """SELECT user_id FROM password_reset_tokens
                   WHERE token_hash = ? AND used_at IS NULL AND expires_at > ?""",
                (token_hash, now)
            ).fetchone()

        if not reset_record:
            return render_template(
                "reset_password.html",
                invalid_token=True
            ), 400

        if request.method == "POST":
            if not valid_csrf():
                flash("Your session expired. Please try again.", "error")
                return redirect(url_for("reset_password", token=token))

            password = request.form.get("password", "")
            confirm_password = request.form.get("confirm_password", "")

            if len(password) < 8:
                flash("Password must contain at least 8 characters.", "error")
                return render_template("reset_password.html", invalid_token=False)

            if password != confirm_password:
                flash("Passwords do not match.", "error")
                return render_template("reset_password.html", invalid_token=False)

            with get_db() as db:
                cursor = db.execute(
                    """UPDATE password_reset_tokens
                       SET used_at = ?
                       WHERE token_hash = ? AND used_at IS NULL AND expires_at > ?""",
                    (now, token_hash, now)
                )

                if cursor.rowcount != 1:
                    return render_template(
                        "reset_password.html",
                        invalid_token=True
                    ), 400

                db.execute(
                    "UPDATE users SET password_hash = ? WHERE id = ?",
                    (generate_password_hash(password), reset_record["user_id"])
                )
                db.execute(
                    "DELETE FROM password_reset_tokens WHERE user_id = ? AND token_hash != ?",
                    (reset_record["user_id"], token_hash)
                )

            flash("Your password has been reset. Please sign in.", "success")
            return redirect(url_for("login"))

        return render_template("reset_password.html", invalid_token=False)

    @app.route("/logout", methods=["POST"])
    def logout():

        if not valid_csrf():
            return jsonify({
                "success": False,
                "error": "Invalid security token."
            }), 400

        session.clear()
        flash("You have been logged out.", "success")
        return redirect(url_for("login"))
